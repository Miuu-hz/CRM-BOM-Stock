  const [loading, setLoading] = useState(true)
  // ตัวกรองทั้งหมดอยู่ใน URL — รีเฟรช/แชร์ลิงก์แล้วได้ผลกรองเดิม
  const [searchParams, setSearchParams] = useSearchParams()
  const filterKey = searchParams.toString()
  const filters = useMemo(() => readFilters(new URLSearchParams(filterKey)), [filterKey])
  const updateFilters = (patch: Partial<JournalFilters>) =>
    setSearchParams(writeFilters({ ...filters, ...patch }), { replace: true })
  const [typeCounts, setTypeCounts] = useState<TypeCount[]>([])
  const [currentPage, setCurrentPage] = useState(1)
  const [showCreateModal, setShowCreateModal] = useState(false)
  const [showQuickModal, setShowQuickModal] = useState(false)
  const [showPayrollModal, setShowPayrollModal] = useState(false)
  const [selectedEntry, setSelectedEntry] = useState<Entry | null>(null)
  const [loadingDetail, setLoadingDetail] = useState(false)

  // กรองรัว ๆ แล้ว response กลับมาไม่ตรงลำดับ — ใช้เฉพาะผลของ request ล่าสุด
  const latestReq = useRef(0)
  const fetchEntries = useCallback(async () => {
    const reqId = ++latestReq.current
    setLoading(true)
    try {
      const res = await journalApi.getAll(toApiParams(filters))
      if (reqId !== latestReq.current) return
      if (res.data.success) {
        const list = (res.data.data as RawEntry[]).map(normalizeEntry)
        setEntries(list)
        setTypeCounts(res.data.meta?.typeCounts ?? [])
        // One bulk call for the whole list — never one attachments request per row.
        const refs = [...new Set(list.map(evidenceKeyFor).filter((k): k is string => !!k))]
        if (refs.length) {
          journalApi.getAttachmentCounts(refs)
            .then(r => { if (r.data.success) setEvidenceCounts(r.data.data) })
            .catch(() => setEvidenceCounts({}))
        } else {
          setEvidenceCounts({})
        }
      }
    } catch (err: any) {
      if (reqId === latestReq.current) toast.error(err.response?.data?.message || 'ไม่สามารถโหลดข้อมูลสมุดรายวันได้')
    } finally {
      if (reqId === latestReq.current) setLoading(false)
    }
  }, [filters])

  useEffect(() => { fetchEntries() }, [fetchEntries])

  // ก4: เปลี่ยนตัวกรองหรือค้นหาแล้วต้องกลับไปหน้าแรกเสมอ ไม่งั้นค้างอยู่หน้าท้าย ๆ ที่อาจไม่เหลือข้อมูล
  useEffect(() => { setCurrentPage(1) }, [filterKey])

  const getEvidenceCount = (entry: Entry): number | undefined => {
    const key = evidenceKeyFor(entry)
    return key ? evidenceCounts[key] : undefined
  }

  const [accountsLoaded, setAccountsLoaded] = useState(false)

  useEffect(() => {
    // ก3: dropdown กรองตามบัญชีอยู่บนหน้าหลักตลอดเวลา เลยต้องโหลดผังบัญชีทันทีที่เข้าหน้า
    // ไม่ใช่รอผู้ใช้เปิดโมดัลบันทึกรายการก่อนเหมือนเดิม
    if (accountsLoaded) return
    accountsApi.getAll({ active: true })
      .then(res => {
        if (res.data.success) {
          const all: Account[] = res.data.data.list
          const parentIds = new Set(all.map((a: Account) => a.parentId).filter(Boolean))
          // show leaf accounts (no children) — or fallback to all if everything is flat (no parent_id set)
          const leaves = all.filter((a: Account) => !parentIds.has(a.id))
          setAccounts(leaves.length > 0 ? leaves : all)
        }
        setAccountsLoaded(true)
      })
      .catch(() => {
        toast.error('ไม่สามารถโหลดผังบัญชีได้')
        setAccountsLoaded(true)
      })
  }, [accountsLoaded])

  const openDetail = async (entry: Entry) => {
    setSelectedEntry(entry)
    if (!entry.lines) {
      setLoadingDetail(true)
      try {
        const res = await journalApi.getById(entry.id)
        if (res.data.success) setSelectedEntry(normalizeEntry(res.data.data))
      } catch { toast.error('โหลดรายละเอียดไม่สำเร็จ') }
      finally { setLoadingDetail(false) }
    }
  }

  const handlePost = async (id: string, e: React.MouseEvent) => {
    e.stopPropagation()
    try {
      await journalApi.post(id)
      toast.success('ยืนยันรายการสำเร็จ')
      fetchEntries()
    } catch (err: any) { toast.error(err.response?.data?.message || 'ยืนยันไม่สำเร็จ') }
  }

  const handleDelete = async (id: string, isPosted: boolean, e: React.MouseEvent) => {
    e.stopPropagation()
    if (isPosted) { toast.error('ไม่สามารถลบรายการที่ยืนยันแล้ว'); return }
    if (!confirm('ต้องการลบรายการนี้?')) return
    try {
      await journalApi.delete(id)
      toast.success('ลบสำเร็จ')
      fetchEntries()
    } catch (err: any) { toast.error(err.response?.data?.message || 'ลบไม่สำเร็จ') }
  }

  const [unpostTarget, setUnpostTarget] = useState<Entry | null>(null)
  const [reverseTarget, setReverseTarget] = useState<Entry | null>(null)

